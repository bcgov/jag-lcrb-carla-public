#!/usr/bin/env node
/** Regenerates src/app/shared/ui/primitives/icons.ts (the registry behind <svg lucide="…">): keeps current entries and adds the given lucide names or aliases, e.g. `pnpm icons AlertCircle Building2`. */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const vanilla = readFileSync(path.join(root, 'node_modules/lucide/dist/esm/lucide/src/lucide.js'), 'utf8');
const registryPath = path.join(root, 'src/app/shared/ui/primitives/icons.ts');

const canonical = new Map();
for (const [, names, file] of vanilla.matchAll(/export \{([^}]*)\} from '\.\/icons\/([\w-]+)\.js'/g)) {
  for (const [, n] of names.matchAll(/as (\w+)/g)) if (!canonical.has(n)) canonical.set(n, file);
}
const pascal = (k) => {
  const s = k.replace(/^([A-Z])|[\s\-_]+(\w)/g, (_m, a, b) => (b ? b.toUpperCase() : a.toLowerCase()));
  return s[0].toUpperCase() + s.slice(1);
};

const existing = [...readFileSync(registryPath, 'utf8').matchAll(/^ {2}(\w+): \['/gm)].map((m) => m[1]);
const names = [...new Set([...existing, ...process.argv.slice(2)])].sort();

const imports = new Map();
const entries = names.map((n) => {
  // lucide-react also exports every icon as `XIcon` and `LucideX`.
  const kebab = canonical.get(n) ?? canonical.get(n.replace(/Icon$/, '')) ?? canonical.get(n.replace(/^Lucide/, ''));
  if (!kebab) throw new Error(`Unknown lucide icon: ${n}`);
  const p = pascal(kebab);
  if (!new RegExp(`\\b${p}\\b`).test(vanilla)) throw new Error(`lucide has no export ${p} (for ${n})`);
  imports.set(p, kebab);
  return `  ${n}: ['${kebab}', ${p}],`;
});

writeFileSync(
  registryPath,
  `/** Generated by tools/gen-icons.mjs (pnpm icons <Name…>); do not edit by hand. */
// Deep imports per icon: the 'lucide' entry resolves to its CommonJS build, which bundles every icon.
import type { IconNode } from 'lucide';
${[...imports.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([p, k]) => `import ${p} from 'lucide/dist/esm/lucide/src/icons/${k}.js';`)
  .join('\n')}

export const ICONS = {
${entries.join('\n')}
} satisfies Record<string, readonly [string, IconNode]>;

export type IconName = keyof typeof ICONS;
`,
);
console.log(`${entries.length} icons in ${path.relative(root, registryPath)}`);
