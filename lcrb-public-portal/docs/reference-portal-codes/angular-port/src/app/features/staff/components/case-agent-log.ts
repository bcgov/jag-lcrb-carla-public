/** Read-only staff record of the AI triage agent's run on a case; prototype data, in production the persisted run stored with the case in Dynamics. */
import { ChangeDetectionStrategy, Component, computed, input } from '@angular/core';
import { LucideIcon } from '@shared/ui/primitives/lucide-icon';
import { Progress } from '@shared/ui/primitives/progress';
import { Separator } from '@shared/ui/primitives/separator';
import { confidenceBand } from '@domain/staff/agent-log';
import { type AgentLog } from '@domain/models/staff';
import { FitAndProperPanel } from './fit-and-proper-panel';
import { OutcomeBadge, QueueBadge } from './queue-badge';

const BAND_TEXT: Record<'high' | 'medium' | 'low', string> = {
  high: 'text-green-700',
  medium: 'text-orange-700',
  low: 'text-red-700',
};

@Component({
  selector: 'case-agent-log',
  imports: [LucideIcon, Progress, Separator, OutcomeBadge, QueueBadge, FitAndProperPanel],
  changeDetection: ChangeDetectionStrategy.OnPush,
  host: { style: 'display: contents' },
  template: `
    <div class="space-y-5">
      <!-- Summary header -->
      <div class="rounded-lg border border-border bg-muted/40 p-4">
        <div class="flex items-start gap-3">
          <div class="rounded-md bg-[#013366] p-2 text-white shrink-0">
            <svg lucide="Bot" class="h-4 w-4"></svg>
          </div>
          <div class="min-w-0">
            <p class="text-sm font-medium text-foreground">Pre-screening summary</p>
            <p class="text-sm text-muted-foreground mt-1 text-pretty">{{ log().summary }}</p>
          </div>
        </div>

        <div class="mt-4 grid gap-4 sm:grid-cols-2">
          <div>
            <div class="flex items-center justify-between text-xs mb-1">
              <span class="text-muted-foreground">Overall confidence</span>
              <span [class]="'font-semibold ' + bandText()">{{ log().overallConfidence }}%</span>
            </div>
            <div uiProgress [value]="log().overallConfidence" class="h-2"></div>
          </div>
          <div class="flex items-center gap-2 text-sm">
            @if (log().requiresHumanReview) {
              <svg lucide="ShieldAlert" class="h-4 w-4 text-orange-600 shrink-0"></svg>
              <span class="text-foreground">Human review required</span>
            } @else {
              <svg lucide="CheckCircle2" class="h-4 w-4 text-green-600 shrink-0"></svg>
              <span class="text-foreground">No mandatory review flag</span>
            }
          </div>
        </div>

        <div class="mt-4 flex flex-wrap items-center gap-2 text-xs text-muted-foreground">
          <span>Routed to</span>
          <queue-badge [queue]="log().recommendedQueue" />
          <span class="hidden sm:inline">·</span>
          <span class="w-full sm:w-auto">{{ log().queueRationale }}</span>
        </div>
      </div>

      <!-- Per-check breakdown -->
      <div>
        <h4 class="text-sm font-semibold text-foreground mb-3">Checks performed</h4>
        <ul class="space-y-3">
          @for (check of log().checks; track check.kind; let i = $index) {
            <li class="rounded-lg border border-border p-3">
              <div class="flex items-center justify-between gap-2">
                <span class="text-sm font-medium text-foreground">{{ check.label }}</span>
                <div class="flex items-center gap-2">
                  <span class="text-xs text-muted-foreground">{{ check.confidence }}%</span>
                  <outcome-badge [outcome]="check.outcome" />
                </div>
              </div>
              <p class="text-sm text-muted-foreground mt-1.5">{{ check.finding }}</p>
              @if (check.observations.length > 0) {
                <ul class="mt-2 space-y-0.5">
                  @for (obs of check.observations; track $index) {
                    <li class="text-xs text-muted-foreground flex gap-1.5">
                      <span aria-hidden="true" class="text-muted-foreground/60">•</span>
                      <span>{{ obs }}</span>
                    </li>
                  }
                </ul>
              }
              @if (i < log().checks.length - 1) {
                <div uiSeparator class="mt-3 sm:hidden"></div>
              }
            </li>
          }
        </ul>
      </div>

      <!-- Fit & proper deep-dive (cannabis apps; liquor new-licence/transfer) -->
      @if (log().fitAndProper; as fp) {
        @if (fp.applicable) {
        <fit-and-proper-panel [style.display]="'block'" [fp]="fp" [applicantName]="applicantName()" />
        }
      }

      <p class="text-xs text-muted-foreground">
        Generated by {{ log().model }} · The agent triages only; an LCRB analyst makes the final
        determination.
      </p>
    </div>
  `,
})
export class CaseAgentLog {
  readonly log = input.required<AgentLog>();
  readonly applicantName = input<string | undefined>(undefined);
  protected readonly bandText = computed(() => BAND_TEXT[confidenceBand(this.log().overallConfidence)]);
}
